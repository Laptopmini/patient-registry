// Writes a typed declaration next to every CSS Module (`Foo.module.css` gets
// `Foo.module.d.css.ts`), so `styles.className` is checked and typos fail `tsc`.
// The declarations are generated and git-ignored; `pnpm typecheck` and `pnpm build` run this first.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../src', import.meta.url).pathname;

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (entry.name.endsWith('.module.css')) yield path;
  }
}

for (const file of walk(root)) {
  const css = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const names = new Set();
  for (const match of css.matchAll(/\.(-?[_a-zA-Z][_a-zA-Z0-9-]*)/g)) names.add(match[1]);
  const body = [...names]
    .sort()
    .map((name) => `  readonly ${JSON.stringify(name)}: string;`)
    .join('\n');
  const out = `// Generated by scripts/css-types.mjs. Do not edit.\ndeclare const styles: {\n${body}\n};\nexport default styles;\n`;
  writeFileSync(file.replace(/\.css$/, '.d.css.ts'), out);
}
