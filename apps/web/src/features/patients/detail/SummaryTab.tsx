import { Link } from '@tanstack/react-router';
import { FileText, Sparkles, TriangleAlert } from 'lucide-react';
import { useGetPatientSummary } from '../../../api/generated/client';
import { unwrap } from '../../../api/unwrap';
import { Button } from '../../../components/ui/Button';
import { EmptyState } from '../../../components/ui/EmptyState';
import { Skeleton } from '../../../components/ui/Skeleton';
import { bloodTypeLabel, formatDateTime } from '../../../lib/format';
import styles from './Detail.module.css';

function Provenance({ provider }: { provider: string }) {
  if (provider === 'anthropic') {
    return (
      <span className={`${styles.provenance} ${styles.provenanceAi}`}>
        <Sparkles />
        AI-generated, verify before clinical use
      </span>
    );
  }
  return (
    <span className={`${styles.provenance} ${styles.provenanceTemplate}`}>
      <FileText />
      {provider === 'template' ? 'Generated from a template' : `Generated by ${provider}`}
    </span>
  );
}

function SummarySkeleton() {
  return (
    <div className={styles.summary} aria-busy="true">
      <p role="status" className="visually-hidden">
        Loading summary…
      </p>
      <Skeleton width="260px" height="28px" pill />
      <div className={styles.identifiers}>
        {[0, 1, 2].map((i) => (
          <div key={i} className={styles.summarySection}>
            <Skeleton width="40%" height="16px" />
            <Skeleton width="70%" />
          </div>
        ))}
      </div>
      <div className={styles.summarySection}>
        <div className={styles.skeletonRow}>
          <Skeleton width="100px" height="32px" pill />
          <Skeleton width="120px" height="32px" pill />
        </div>
        <div className={styles.skeletonRow}>
          <Skeleton width="90px" height="32px" pill />
          <Skeleton width="110px" height="32px" pill />
        </div>
      </div>
      <div className={styles.summarySection}>
        <Skeleton />
        <Skeleton />
        <Skeleton />
        <Skeleton width="60%" />
      </div>
    </div>
  );
}

export function SummaryTab({ patientId }: { patientId: string }) {
  const { data, isPending, isError, refetch } = useGetPatientSummary(patientId, {
    query: { select: unwrap },
  });

  if (isError) {
    return (
      <div className={styles.summary}>
        <EmptyState
          tone="error"
          headingLevel={3}
          title="We couldn't generate the summary."
          action={
            <Button variant="primary" onPress={() => void refetch()}>
              Retry
            </Button>
          }
        >
          The rest of the page still works.
        </EmptyState>
      </div>
    );
  }

  if (isPending) return <SummarySkeleton />;

  const paragraphs = data.narrative.split(/\n+/).filter((p) => p.trim() !== '');

  return (
    <section aria-labelledby="summary-title" className={styles.summary}>
      <div className={styles.summaryHead}>
        <div>
          <h2 id="summary-title">Summary</h2>
          <Provenance provider={data.provider} />
        </div>
      </div>

      <div className={styles.summarySection}>
        <h3>Identifiers</h3>
        <dl className={styles.identifiers}>
          <div>
            <dt>Name</dt>
            <dd>{data.name}</dd>
          </div>
          <div>
            <dt>Age</dt>
            <dd>{data.age} y</dd>
          </div>
          <div>
            <dt>Blood type</dt>
            <dd>{bloodTypeLabel(data.blood_type)}</dd>
          </div>
        </dl>
      </div>

      <div className={styles.summarySection}>
        <h3>Key clinical facts</h3>
        <div>
          <p className={styles.groupLabel}>Conditions</p>
          {data.conditions.length ? (
            <ul className={styles.chips}>
              {data.conditions.map((name) => (
                <li key={name} className={styles.chip}>
                  {name}
                </li>
              ))}
            </ul>
          ) : (
            <p className={styles.muted}>None recorded</p>
          )}
        </div>
        <div>
          <p className={styles.groupLabel}>Allergies</p>
          {data.allergies.length ? (
            <ul className={styles.chips}>
              {data.allergies.map((name) => (
                <li key={name} className={`${styles.chip} ${styles.chipAllergy}`}>
                  <TriangleAlert />
                  {name}
                </li>
              ))}
            </ul>
          ) : (
            <p className={styles.muted}>No known allergies</p>
          )}
        </div>
      </div>

      <div className={styles.summarySection}>
        <h3>Narrative</h3>
        {data.note_count === 0 ? (
          <div className={styles.noNotes}>
            <p>No notes yet, so there's nothing to summarise.</p>
            <Link to="/patients/$patientId/notes" params={{ patientId }}>
              Add the first note
            </Link>
          </div>
        ) : (
          <div className={styles.narrative}>
            {paragraphs.map((paragraph) => (
              <p key={paragraph}>{paragraph}</p>
            ))}
          </div>
        )}
      </div>

      <p className={styles.summaryFoot}>
        Based on {data.note_count} {data.note_count === 1 ? 'note' : 'notes'} · Generated{' '}
        {formatDateTime(data.generated_at)}
      </p>
    </section>
  );
}
