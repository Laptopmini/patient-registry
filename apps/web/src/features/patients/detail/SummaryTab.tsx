import { useGetPatientSummary } from '../../../api/generated/client';
import { unwrap } from '../../../api/unwrap';
import { ErrorState } from '../../../components/ui/ErrorState';
import { bloodTypeLabel } from '../../../lib/format';
import styles from './Detail.module.css';

const PROVIDER_LABELS: Record<string, string> = {
  template: 'Generated from a template',
  anthropic: 'AI-generated, verify before clinical use',
};

export function SummaryTab({ patientId }: { patientId: string }) {
  const { data, isPending, isError, refetch } = useGetPatientSummary(patientId, {
    query: { select: unwrap },
  });

  if (isError) {
    return <ErrorState message="We couldn't load the summary." onRetry={() => void refetch()} />;
  }

  if (isPending) {
    return (
      <div aria-busy="true" role="status">
        <span className="visually-hidden">Loading summary…</span>
        <div className={styles.skeleton} />
        <div className={styles.skeleton} />
        <div className={`${styles.skeleton} ${styles.skeletonTall}`} />
      </div>
    );
  }

  const paragraphs = data.narrative.split(/\n+/).filter((p) => p.trim() !== '');

  return (
    <div className={styles.summary}>
      <section aria-labelledby="summary-ids">
        <h2 id="summary-ids">Identifiers</h2>
        <dl className={styles.facts}>
          <div>
            <dt>Name</dt>
            <dd>{data.name}</dd>
          </div>
          <div>
            <dt>Age</dt>
            <dd>{data.age} y</dd>
          </div>
          <div>
            <dt>Blood type</dt>
            <dd>{bloodTypeLabel(data.blood_type)}</dd>
          </div>
        </dl>
      </section>

      <section aria-labelledby="summary-facts">
        <h2 id="summary-facts">Key clinical facts</h2>
        <dl className={styles.facts}>
          <div>
            <dt>Conditions</dt>
            <dd>{data.conditions.length ? data.conditions.join(', ') : 'None recorded'}</dd>
          </div>
          <div>
            <dt>Allergies</dt>
            <dd>{data.allergies.length ? data.allergies.join(', ') : 'No known allergies'}</dd>
          </div>
        </dl>
      </section>

      <section aria-labelledby="summary-narrative">
        <h2 id="summary-narrative">Narrative</h2>
        {data.note_count === 0 ? (
          <p>No notes yet, so there's nothing to summarise.</p>
        ) : (
          paragraphs.map((paragraph) => <p key={paragraph}>{paragraph}</p>)
        )}
        <p className={styles.provenance}>
          <strong>{PROVIDER_LABELS[data.provider] ?? `Generated by ${data.provider}`}</strong>
          {' · '}
          Based on {data.note_count} {data.note_count === 1 ? 'note' : 'notes'}
        </p>
      </section>
    </div>
  );
}
